import { motion } from 'framer-motion'
import { AlertTriangle, ChevronDown, Clock, Flag, Gauge, GitFork, Ruler, Star, Zap } from 'lucide-react'
import { useState } from 'react'

import type { PlannedRoute, RiskLevel } from '../api/types'
import { fmtDay, fmtDayTime, fmtDuration, fmtDurationDelta, fmtKm, fmtMiles, fmtTime } from '../lib/format'
import { LEVEL_BG, LEVEL_COLORS, LEVEL_LABELS, routeColor } from '../lib/risk'
import { useStore } from '../store'
import { RiskRibbon } from './RiskRibbon'

interface Props {
  route: PlannedRoute
  selected: boolean
  fastestDuration: number
  truckMile: number | null
}

export function RouteCard({ route, selected, fastestDuration, truckMile }: Props) {
  const [expanded, setExpanded] = useState(false)
  const selectRoute = useStore((s) => s.selectRoute)
  const hoverRoute = useStore((s) => s.hoverRoute)
  const setActive = useStore((s) => s.setActiveCheckpoint)
  const activeCp = useStore((s) => s.activeCheckpoint)
  const color = routeColor(route.id)
  const s = route.summary
  const isFastest = route.duration_s === fastestDuration
  const delta = route.duration_s - fastestDuration
  const worst = route.checkpoints[s.worst_checkpoint_index] ?? route.checkpoints[0]

  return (
    <motion.article
      layout
      initial={{ opacity: 0, y: 12 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.3, delay: 0.05 * (route.id.charCodeAt(0) - 65) }}
      onMouseEnter={() => hoverRoute(route.id)}
      onMouseLeave={() => hoverRoute(null)}
      className={`glass cursor-pointer rounded-2xl p-4 transition-all duration-200 ${
        selected ? 'ring-2 ring-sky-400/60 shadow-glow' : 'hover:-translate-y-0.5 hover:border-white/20'
      }`}
      onClick={() => selectRoute(route.id)}
      aria-selected={selected}
    >
      <div className="flex items-start gap-3">
        <div
          className="mt-0.5 grid h-8 w-8 shrink-0 place-items-center rounded-lg text-sm font-extrabold text-ink-950"
          style={{ background: color }}
        >
          {route.id}
        </div>
        <div className="min-w-0 flex-1">
          <div className="flex flex-wrap items-center gap-1.5">
            <h3 className="text-sm font-bold text-white">{route.name}</h3>
            {route.recommended && (
              <span className="inline-flex items-center gap-1 rounded-full bg-sky-400/15 px-2 py-0.5 text-[10px] font-bold uppercase tracking-wide text-sky-200 ring-1 ring-sky-400/40">
                <Star className="h-3 w-3 fill-current" /> Recommended
              </span>
            )}
            {isFastest && (
              <span className="inline-flex items-center gap-1 rounded-full bg-white/[0.06] px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wide text-slate-300 ring-1 ring-white/10">
                <Zap className="h-3 w-3" /> Fastest
              </span>
            )}
            {route.synthetic && (
              <span
                className="inline-flex items-center gap-1 rounded-full bg-white/[0.06] px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wide text-slate-400 ring-1 ring-white/10"
                title="Generated by routing through a lateral via-point because the provider returned fewer than 3 alternatives"
              >
                <GitFork className="h-3 w-3" /> Alt corridor
              </span>
            )}
          </div>
          <p className="mt-0.5 text-xs text-slate-400">
            Rank #{route.rank} &middot; worst segment{' '}
            <span className={`font-semibold ${LEVEL_BG[s.max_level].split(' ')[1]}`}>{s.max_label}</span>
          </p>
        </div>
      </div>

      <div className="mt-3">
        <RiskRibbon checkpoints={route.checkpoints} totalMiles={s.total_miles} marker={selected ? truckMile : null} />
        <div className="mt-1 flex justify-between font-mono text-[10px] text-slate-500">
          <span>{fmtTime(route.departure)}</span>
          <span>{fmtMiles(s.total_miles)}</span>
          <span>{fmtTime(route.eta)}</span>
        </div>
      </div>

      <dl className="mt-3 grid grid-cols-4 gap-2">
        <Stat icon={Ruler} label="Distance" value={fmtMiles(route.distance_mi)} sub={fmtKm(route.distance_mi)} />
        <Stat icon={Clock} label="Drive" value={fmtDuration(route.duration_s)} sub={isFastest ? undefined : fmtDurationDelta(delta)} />
        <Stat icon={Flag} label="Arrive" value={fmtTime(route.eta)} sub={fmtDay(route.eta)} />
        <Stat icon={Gauge} label="Avg risk" value={s.avg_risk.toFixed(2)} sub="/ 4" />
      </dl>

      <div className="mt-3 flex flex-wrap gap-1.5">
        {s.miles_by_level.map((miles, level) =>
          miles > 0 ? (
            <span
              key={level}
              className={`inline-flex items-center gap-1.5 rounded-md px-2 py-1 text-[11px] font-semibold ring-1 ${LEVEL_BG[level as RiskLevel]}`}
            >
              <span className="h-1.5 w-1.5 rounded-full" style={{ background: LEVEL_COLORS[level as RiskLevel] }} />
              {LEVEL_LABELS[level]} {fmtMiles(miles)}
            </span>
          ) : null,
        )}
      </div>

      {worst.risk.level >= 1 && (
        <button
          type="button"
          onClick={(e) => {
            e.stopPropagation()
            selectRoute(route.id)
            setActive({ routeId: route.id, index: worst.index, pinned: true, focus: true })
          }}
          className="mt-3 flex w-full items-center gap-2 rounded-lg border px-3 py-2 text-left text-[11px] transition hover:brightness-125"
          style={{ borderColor: `${LEVEL_COLORS[worst.risk.level]}55`, background: `${LEVEL_COLORS[worst.risk.level]}14` }}
          title="Show the worst checkpoint on the map"
        >
          <AlertTriangle className="h-3.5 w-3.5 shrink-0" style={{ color: LEVEL_COLORS[worst.risk.level] }} />
          <span className="min-w-0 flex-1 truncate text-slate-200">
            <b style={{ color: LEVEL_COLORS[worst.risk.level] }}>{worst.risk.label}</b> at mile {worst.mile.toFixed(0)} &middot; {fmtDayTime(worst.eta)}{' '}
            &middot; {worst.risk.drivers[0]}
          </span>
        </button>
      )}

      <button
        type="button"
        onClick={(e) => {
          e.stopPropagation()
          setExpanded((v) => !v)
        }}
        className="mt-3 flex w-full items-center justify-between rounded-lg border border-white/10 bg-white/[0.03] px-3 py-2 text-xs font-semibold text-slate-300 transition hover:bg-white/[0.06]"
        aria-expanded={expanded}
      >
        <span>
          {s.checkpoint_count} checkpoints &middot; {route.provider === 'osrm' ? 'OSRM' : 'ORS truck profile'}
        </span>
        <ChevronDown className={`h-4 w-4 transition ${expanded ? 'rotate-180' : ''}`} />
      </button>

      {expanded && (
        <div className="mt-2 max-h-72 overflow-y-auto rounded-lg border border-white/10 scroll-thin">
          <table className="w-full text-left text-[11px]">
            <thead className="sticky top-0 bg-ink-800/95 text-[10px] uppercase tracking-wider text-slate-400 backdrop-blur">
              <tr>
                <th className="px-2 py-1.5">Mile</th>
                <th className="px-2 py-1.5">ETA</th>
                <th className="px-2 py-1.5 text-right">Wind</th>
                <th className="px-2 py-1.5 text-right">Rain</th>
                <th className="px-2 py-1.5 text-right">Snow</th>
                <th className="px-2 py-1.5">Risk</th>
              </tr>
            </thead>
            <tbody>
              {route.checkpoints.map((cp) => {
                const active = activeCp?.routeId === route.id && activeCp.index === cp.index
                return (
                  <tr
                    key={cp.index}
                    className={`cursor-pointer border-t border-white/5 font-mono transition hover:bg-white/[0.05] ${active ? 'bg-sky-400/10' : ''}`}
                    onClick={(e) => {
                      e.stopPropagation()
                      selectRoute(route.id)
                      setActive({ routeId: route.id, index: cp.index, pinned: true, focus: true })
                    }}
                  >
                    <td className="px-2 py-1.5 text-slate-300">{cp.mile.toFixed(0)}</td>
                    <td className="px-2 py-1.5 text-slate-300">{fmtDayTime(cp.eta)}</td>
                    <td className="px-2 py-1.5 text-right text-slate-300">{cp.weather.wind_mph.toFixed(0)}</td>
                    <td className="px-2 py-1.5 text-right text-slate-300">{cp.weather.rain_in_hr.toFixed(2)}</td>
                    <td className="px-2 py-1.5 text-right text-slate-300">{cp.weather.snow_in_hr.toFixed(1)}</td>
                    <td className="px-2 py-1.5">
                      <span className="inline-flex items-center gap-1.5 font-sans font-semibold" style={{ color: LEVEL_COLORS[cp.risk.level] }}>
                        <span className="h-2 w-2 rounded-full" style={{ background: LEVEL_COLORS[cp.risk.level] }} />
                        {cp.risk.label}
                      </span>
                    </td>
                  </tr>
                )
              })}
            </tbody>
          </table>
        </div>
      )}
    </motion.article>
  )
}

function Stat({
  icon: Icon,
  label,
  value,
  sub,
}: {
  icon: typeof Ruler
  label: string
  value: string
  sub?: string
}) {
  return (
    <div className="rounded-lg bg-white/[0.03] px-2 py-1.5">
      <dt className="flex items-center gap-1 text-[10px] uppercase tracking-wider text-slate-500">
        <Icon className="h-3 w-3" /> {label}
      </dt>
      <dd className="mt-0.5 text-[13px] font-semibold leading-tight text-slate-100">
        <span className="block truncate">{value}</span>
        {sub && <span className="block truncate text-[10px] font-medium text-slate-500">{sub}</span>}
      </dd>
    </div>
  )
}
